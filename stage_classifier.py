# -*- coding: utf-8 -*-
"""
stage_classifier.py
Определение "Этапа работ" для колонки "Этап" сводной таблицы.

Два источника, в порядке приоритета:

1. MANUAL_STAGE_RULES — правила, заданные пользователем вручную поверх
   статистики (см. переписку по каждому "Виду работ" — пользователь построчно
   разбирал спорные случаи из справочника ниже). Всегда имеют приоритет: они
   точнее статистики, потому что учитывают знание предметной области, которого
   нет в трёх колонках справочника.

2. stage_classification.json — статистический справочник, собранный из файла
   "Этапы работ.xlsx" (~186 тыс. исторических строк хронологии буровых работ
   ООО "ИНК"), три уровня соответствий:
     - triples: ключ "вид\x1fоперация\x1fдетализация" -> этап
     - pairs:   ключ "вид\x1fоперация"                 -> этап
     - vids:    ключ "вид"                              -> этап
   Для неоднозначных исторических комбинаций (одна и та же тройка встречается
   в реальных данных с разными этапами) в справочнике сохранено большинство
   голосов (самый частый этап) — это применяется только там, где пользователь
   ещё не задал точное ручное правило (п.1).

Особый случай — ПРЕДУПРЕЖДЕНИЕ вместо этапа: механизм поддерживает пометку
конкретной операции как {"warning": "..."} — тогда вместо гадательного этапа
в отчёте показывается предупреждающий значок с всплывающей подсказкой. На
данный момент все размеченные вручную виды работ получили точный этап (см.
MANUAL_STAGE_RULES ниже), но механизм оставлен на случай новых спорных
случаев в будущем.

classify_stage(vid, op, det) возвращает пару (этап_или_None,
предупреждение_или_None). Если оба None — значит, ни ручные правила, ни
статистический справочник не дали ответа, и вызывающий код (extract_current_stage
в sr_parser.py) в качестве последнего запасного варианта использует сырой
текст ячейки "Этап работ" из самого рапорта.
"""

import json
import os
import sys


def _base_dir():
    """Папка с ресурсами программы: при обычном запуске — рядом с этим .py
    файлом; при запуске из .exe, собранного PyInstaller-ом — временная папка,
    куда PyInstaller распаковывает приложенные данные, см. build.bat."""
    if getattr(sys, "frozen", False):
        return getattr(sys, "_MEIPASS", os.path.dirname(os.path.abspath(sys.executable)))
    return os.path.dirname(os.path.abspath(__file__))


_DATA_PATH = os.path.join(_base_dir(), "stage_classification.json")

_data = None  # ленивая загрузка, чтобы отсутствие файла не мешало импорту модуля


def _load():
    global _data
    if _data is not None:
        return _data
    try:
        with open(_DATA_PATH, "r", encoding="utf-8") as f:
            _data = json.load(f)
    except (OSError, ValueError):
        _data = {}
    return _data


def _norm(v):
    if v is None:
        return ""
    return str(v).strip().lower()


_NO_OP_WARNING = "В хронологии работ нет указанной операции (пусто)"

# ---------------------------------------------------------------------------
# Ручные правила пользователя (приоритет выше статистического справочника).
# Ключ верхнего уровня — нормализованный (lower+strip) "Вид работ". Значение:
#
#   - строка "Этап"  -> БЛАНКЕТНОЕ правило: весь этот "Вид работ" всегда
#     считается этим этапом, независимо от "Операции"/"Детализации" (в т.ч.
#     когда они пустые). Используется там, где сам вид работ однозначно
#     принадлежит одной фазе (например, монтаж/демонтаж буровой — это всегда
#     ВМР и ПНР, вне зависимости от конкретной операции).
#
#   - словарь { нормализованная "Операция": "Этап" (или {"warning": "..."}) }
#     -> точечные правила ПО ОПЕРАЦИЯМ этого вида работ. Операция, которой
#     нет в словаре (в т.ч. пустая "") — НЕ покрыта ручным правилом и уходит
#     в статистический справочник stage_classification.json как обычно.
#     Используется там, где сам "Вид работ" слишком общий и встречается в
#     разных фазах (например, "Вспомогательные работы") — тогда размечены
#     только конкретные операции, про которые известно наверняка.
# ---------------------------------------------------------------------------
MANUAL_STAGE_RULES = {
    # Монтаж/демонтаж и передвижка буровой установки, ПНР — всегда ВМР и ПНР,
    # какая бы конкретная операция ни стояла в хронологии.
    "демонтаж бу": "ВМР и ПНР",
    "монтаж бу": "ВМР и ПНР",
    "передвижка бу": "ВМР и ПНР",
    "пнр": "ВМР и ПНР",

    # Работы с устьевым оборудованием (ПВО, план-шайба, ФА), сборка
    # внутрискважинного оборудования (стингер, ЭЦН) и спуск НКТ — это уже
    # после того, как скважина пробурена и спущен хвостовик, т.е. Освоение.
    "оборудование устья": "Освоение",
    "сборка внутрискважинного оборудования": "Освоение",
    "спуск нкт": "Освоение",
    "промывка": "Освоение",

    # "Вспомогательные работы" — слишком общий вид работ (встречается не
    # только на этапе освоения), поэтому размечаем только конкретные
    # операции, о которых известно, что они относятся к освоению (после
    # спуска хвостовика); остальные операции этого вида (включая пустую)
    # определяются статистическим справочником, как и раньше.
    "вспомогательные работы": {
        "пзр перед спуском нкт": "Освоение",
        "опрессовка трубных плашек пво": "Освоение",
        "опрессовка фа": "Освоение",
        "опрессовка межколонного пространства": "Освоение",
        "опрессовка межколонного уплотнения": "Освоение",
        "стыковка стингера": "Освоение",
    },
}


def classify_stage(vid, op, det):
    """Возвращает пару (этап_или_None, предупреждение_или_None) по
    (Вид работ, Операция, Детализация операции) строки хронологии.

    Сначала проверяются ручные правила пользователя (MANUAL_STAGE_RULES) для
    данного "Вида работ": бланкетное правило (строка) применяется всегда для
    этого вида работ; точечное правило (словарь по операциям) применяется,
    только если встретившаяся "Операция" в нём явно перечислена. Если
    ручного правила нет (ни бланкетного, ни точечного для этой операции) —
    используется статистический справочник stage_classification.json, с
    постепенным огрублением ключа (тройка -> пара -> только вид)."""
    nvid, nop, ndet = _norm(vid), _norm(op), _norm(det)
    if not nvid:
        return None, None

    manual = MANUAL_STAGE_RULES.get(nvid)
    if isinstance(manual, str):
        return manual, None
    if isinstance(manual, dict) and nop in manual:
        entry = manual[nop]
        if isinstance(entry, dict):
            return None, entry.get("warning")
        return entry, None

    data = _load()
    sep = data.get("sep", "\x1f")

    triples = data.get("triples") or {}
    key = sep.join([nvid, nop, ndet])
    if key in triples:
        return triples[key], None

    pairs = data.get("pairs") or {}
    key = sep.join([nvid, nop])
    if key in pairs:
        return pairs[key], None

    vids = data.get("vids") or {}
    if nvid in vids:
        return vids[nvid], None

    return None, None
